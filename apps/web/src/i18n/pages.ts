export type PageKey = keyof typeof pageEn;
export function usePageT() {
  const { locale } = useLocale();
  return useCallback((key: PageKey, values: Record<string, string | number> = {}) => {
    let message: string = locale === 'en' ? pageEn[key] : key;
    for (const [name, value] of Object.entries(values)) message = message.replaceAll(`{${name}}`, String(value));
    return message;
  }, [locale]);
}
